export function pseudoFor(beat) {
  return PSEUDO[beat?.id] || FALLBACK;
}

for (const [id, tip] of Object.entries(PSEUDO)) {
  const count = tip.lines?.length || 0;
  if (!tip.does || !tip.metaphor || !tip.myth) {
    throw new Error(`伪代码 ${id} 缺了干什么、纸带或误会`);
  }
  if (count < 3 || count > 8) {
    throw new Error(`伪代码 ${id} 要有 3 到 8 行，现在是 ${count}`);
  }
}
