const ALL_BEATS = [
  ...LEVEL1_BEATS,
  ...LEVEL2_BEATS,
  ...LEVEL3_BEATS,
  ...LEVEL4_BEATS,
  ...LEVEL5_BEATS,
  TITLE_BEAT,
  END_BEAT,
];
for (const beat of ALL_BEATS) {
  const ja = JA_BEATS[beat.id];
  if (!ja) throw new Error(`JA beat missing ${beat.id}`);
  for (const key of ["purpose", "caption", "goal", "why", "example", "remember", "footnote"]) {
    if (beat[key] && !ja[key]) throw new Error(`JA ${beat.id}.${key} missing`);
  }
  if (beat.myths?.length && !(ja.myths?.length >= 1)) throw new Error(`JA ${beat.id}.myths missing`);
  if (!SPEECH[beat.id]?.zh || !SPEECH[beat.id]?.ja) throw new Error(`speech line missing ${beat.id}`);
}

for (const [id, tip] of Object.entries(JA_PSEUDO)) {
  const count = tip.lines?.length || 0;
  if (!tip.does || !tip.metaphor || !tip.myth) throw new Error(`JA pseudo ${id} incomplete`);
  if (count < 3 || count > 8) throw new Error(`JA pseudo ${id} has ${count} lines`);
}
