const FALLBACK = {
  does: "这一课先看纸带上的格子。",
  metaphor: "格子还在。先别跳到采样。",
  lines: ["看清这一格在纸带上的位置", "能用的线索只在左边和自己", "答案先放在评分桌上"],
  myth: "不要把还没讲的步骤当成已经发生。",
};

export function pseudoFor(beat) {
  const base = PSEUDO[beat?.id] || FALLBACK;
  if (getLang() !== "ja") return base;
  return JA_PSEUDO[beat?.id] || JA_PSEUDO_FALLBACK;
}

for (const [id, tip] of Object.entries(PSEUDO)) {
  const count = tip.lines?.length || 0;
  if (!tip.does || !tip.metaphor || !tip.myth) {
    throw new Error(`伪代码 ${id} 缺了干什么、纸带或误会`);
  }
  if (count < 3 || count > 8) {
    throw new Error(`伪代码 ${id} 要有 3 到 8 行，现在是 ${count}`);
  }
}
